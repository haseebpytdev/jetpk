const appDir = path.resolve(__dirname, "../app");
const docsDir = path.join(repoRoot, "docs/frontend");

function walkPages(dir, segments = []) {
  const entries = readdirSync(dir);
  const pages = [];
  for (const entry of entries) {
    const full = path.join(dir, entry);
    const st = statSync(full);
    if (st.isDirectory()) {
      pages.push(...walkPages(full, [...segments, entry]));
      continue;
    }
    if (entry === "page.tsx") {
      pages.push({ file: full, segments });
    }
  }
  return pages;
}

function toRoute(segments) {
  const parts = segments
    .filter((s) => !(s.startsWith("(") && s.endsWith(")")))
    .map((s) => (s.startsWith("[") ? `[${s.slice(1, -1)}]` : s));
  return "/" + parts.join("/");
}

